package com.example.demo.controller;

import com.example.demo.repository.*;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.HashMap;
import java.util.Map;
import java.util.concurrent.ExecutionException;

@RestController
@RequestMapping("/api/dashboard")
@CrossOrigin(origins = "*")
public class DashboardController {

    private final StudentRepository studentRepository;
    private final TeacherRepository teacherRepository;
    private final CourseRepository courseRepository;
    private final ClassroomRepository classroomRepository;
    private final TimetableRepository timetableRepository;

    public DashboardController(
            StudentRepository studentRepository,
            TeacherRepository teacherRepository,
            CourseRepository courseRepository,
            ClassroomRepository classroomRepository,
            TimetableRepository timetableRepository) {

        this.studentRepository = studentRepository;
        this.teacherRepository = teacherRepository;
        this.courseRepository = courseRepository;
        this.classroomRepository = classroomRepository;
        this.timetableRepository = timetableRepository;
    }

    @GetMapping("/stats")
    public ResponseEntity<Map<String, Object>> getStats()
            throws ExecutionException, InterruptedException {

        long totalStudents = studentRepository.count();
        long totalTeachers = teacherRepository.count();
        long totalCourses = courseRepository.count();
        long totalClassrooms = classroomRepository.count();
        long totalTimetables = timetableRepository.count();

        long autoGenerated = timetableRepository.findAll()
                .stream()
                .filter(t -> t.isAutoGenerated())
                .count();

        long manual = totalTimetables - autoGenerated;

        Map<String, Object> stats = new HashMap<>();

        stats.put("totalStudents", totalStudents);
        stats.put("totalTeachers", totalTeachers);
        stats.put("totalCourses", totalCourses);
        stats.put("totalClassrooms", totalClassrooms);
        stats.put("totalTimetables", totalTimetables);
        stats.put("manualTimetables", manual);
        stats.put("autoGeneratedTimetables", autoGenerated);

        return ResponseEntity.ok(stats);
    }
}