
package com.example.demo.controller;

import com.example.demo.dto.ApiResponse;
import com.example.demo.dto.TimetableRequest;
import com.example.demo.entity.Timetable;
import com.example.demo.service.TimetableGeneratorService;
import com.example.demo.service.TimetableService;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/timetables")
@CrossOrigin(origins = "*")
public class TimetableController {

    private final TimetableService timetableService;
    private final TimetableGeneratorService timetableGeneratorService;

    public TimetableController(
            TimetableService timetableService,
            TimetableGeneratorService timetableGeneratorService) {

        this.timetableService = timetableService;
        this.timetableGeneratorService = timetableGeneratorService;
    }

    @GetMapping
    public ResponseEntity<List<Timetable>> getAllTimetables() {
        return ResponseEntity.ok(
                timetableService.getAllTimetables()
        );
    }

    @GetMapping("/{id}")
    public ResponseEntity<Timetable> getTimetableById(
            @PathVariable String id) {

        return ResponseEntity.ok(
                timetableService.getTimetableById(id)
        );
    }

    @PostMapping("/teacher/{teacherId}/course/{courseId}/classroom/{classroomId}")
    public ResponseEntity<Timetable> createTimetable(
            @PathVariable String teacherId,
            @PathVariable String courseId,
            @PathVariable String classroomId,
            @Valid @RequestBody TimetableRequest request) {

        Timetable savedTimetable = timetableService.createTimetable(
                request,
                teacherId,
                courseId,
                classroomId
        );

        return new ResponseEntity<>(
                savedTimetable,
                HttpStatus.CREATED
        );
    }

    @PutMapping("/{id}")
    public ResponseEntity<Timetable> updateTimetable(
            @PathVariable String id,
            @Valid @RequestBody TimetableRequest request) {

        Timetable updated = timetableService.updateTimetable(
                id,
                request
        );

        return ResponseEntity.ok(updated);
    }

    @DeleteMapping("/auto-generated")
    public ResponseEntity<ApiResponse<String>> clearAutoGenerated() {

        timetableService.clearAutoGenerated();

        return ResponseEntity.ok(
                ApiResponse.success(
                        "Auto-generated timetables cleared successfully"
                )
        );
    }

    @DeleteMapping("/{id}")
    public ResponseEntity<ApiResponse<String>> deleteTimetable(
            @PathVariable String id) {

        timetableService.deleteTimetable(id);

        return ResponseEntity.ok(
                ApiResponse.success(
                        "Timetable deleted successfully"
                )
        );
    }

    @PostMapping("/generate")
    public ResponseEntity<List<Timetable>> generateTimetable() {

        List<Timetable> generated =
                timetableGeneratorService.generateTimetable();

        return ResponseEntity.ok(generated);
    }

    @GetMapping("/teacher/{teacherId}")
    public ResponseEntity<List<Timetable>> getTimetablesByTeacher(
            @PathVariable String teacherId) {

        return ResponseEntity.ok(
                timetableService.getTimetablesByTeacher(teacherId)
        );
    }

    @GetMapping("/course/{courseId}")
    public ResponseEntity<List<Timetable>> getTimetablesByCourse(
            @PathVariable String courseId) {

        return ResponseEntity.ok(
                timetableService.getTimetablesByCourse(courseId)
        );
    }

    @GetMapping("/classroom/{classroomId}")
    public ResponseEntity<List<Timetable>> getTimetablesByClassroom(
            @PathVariable String classroomId) {

        return ResponseEntity.ok(
                timetableService.getTimetablesByClassroom(classroomId)
        );
    }
}
