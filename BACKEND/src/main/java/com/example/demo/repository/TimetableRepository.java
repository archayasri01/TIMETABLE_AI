
package com.example.demo.repository;

import com.example.demo.entity.Classroom;
import com.example.demo.entity.Course;
import com.example.demo.entity.Teacher;
import com.example.demo.entity.Timetable;
import com.google.cloud.firestore.DocumentSnapshot;
import com.google.cloud.firestore.Firestore;
import com.google.cloud.firestore.QueryDocumentSnapshot;
import org.springframework.stereotype.Repository;

import java.time.LocalTime;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ExecutionException;

@Repository
public class TimetableRepository {

    private final Firestore firestore;

    public TimetableRepository(Firestore firestore) {
        this.firestore = firestore;
    }

    public Timetable save(Timetable timetable)
            throws ExecutionException, InterruptedException {

        String id = timetable.getId();

        if (id == null || id.isBlank()) {
            id = firestore.collection("timetables")
                    .document()
                    .getId();
            timetable.setId(id);
        }

        Map<String, Object> data = new HashMap<>();

        data.put("id", id);
        data.put("day", timetable.getDay());
        data.put("startTime", timetable.getStartTime().toString());
        data.put("endTime", timetable.getEndTime().toString());
        data.put("autoGenerated", timetable.isAutoGenerated());

        data.put("teacher", teacherToMap(timetable.getTeacher()));
        data.put("course", courseToMap(timetable.getCourse()));
        data.put("classroom", classroomToMap(timetable.getClassroom()));

        firestore.collection("timetables")
                .document(id)
                .set(data)
                .get();

        return timetable;
    }

    public Optional<Timetable> findById(String id)
            throws ExecutionException, InterruptedException {

        DocumentSnapshot document = firestore
                .collection("timetables")
                .document(id)
                .get()
                .get();

        if (!document.exists()) {
            return Optional.empty();
        }

        return Optional.of(documentToTimetable(document));
    }

    public List<Timetable> findAll()
            throws ExecutionException, InterruptedException {

        List<Timetable> timetables = new ArrayList<>();

        List<QueryDocumentSnapshot> documents = firestore
                .collection("timetables")
                .get()
                .get()
                .getDocuments();

        for (QueryDocumentSnapshot document : documents) {
            timetables.add(documentToTimetable(document));
        }

        return timetables;
    }

    public List<Timetable> findByCourseId(String courseId)
            throws ExecutionException, InterruptedException {

        return findByNestedId("course.id", courseId);
    }

    public List<Timetable> findByTeacherId(String teacherId)
            throws ExecutionException, InterruptedException {

        return findByNestedId("teacher.id", teacherId);
    }

    public List<Timetable> findByClassroomId(String classroomId)
            throws ExecutionException, InterruptedException {

        return findByNestedId("classroom.id", classroomId);
    }

    private List<Timetable> findByNestedId(String field, String id)
            throws ExecutionException, InterruptedException {

        List<Timetable> timetables = new ArrayList<>();

        List<QueryDocumentSnapshot> documents = firestore
                .collection("timetables")
                .whereEqualTo(field, id)
                .get()
                .get()
                .getDocuments();

        for (QueryDocumentSnapshot document : documents) {
            timetables.add(documentToTimetable(document));
        }

        return timetables;
    }

    public List<Timetable> findByDayOrderByStartTimeAsc(String day)
            throws ExecutionException, InterruptedException {

        List<Timetable> timetables = new ArrayList<>();

        List<QueryDocumentSnapshot> documents = firestore
                .collection("timetables")
                .whereEqualTo("day", day)
                .get()
                .get()
                .getDocuments();

        for (QueryDocumentSnapshot document : documents) {
            timetables.add(documentToTimetable(document));
        }

        timetables.sort(
                Comparator.comparing(Timetable::getStartTime)
        );

        return timetables;
    }

    public void deleteById(String id)
            throws ExecutionException, InterruptedException {

        firestore.collection("timetables")
                .document(id)
                .delete()
                .get();
    }

    public boolean existsById(String id)
            throws ExecutionException, InterruptedException {

        return findById(id).isPresent();
    }

    public long count()
            throws ExecutionException, InterruptedException {

        return firestore.collection("timetables")
                .count()
                .get()
                .get()
                .getCount();
    }

    public void deleteByAutoGeneratedTrue()
            throws ExecutionException, InterruptedException {

        List<QueryDocumentSnapshot> documents = firestore
                .collection("timetables")
                .whereEqualTo("autoGenerated", true)
                .get()
                .get()
                .getDocuments();

        for (QueryDocumentSnapshot document : documents) {
            document.getReference().delete().get();
        }
    }

    public long countTeacherConflict(
            String teacherId,
            String day,
            LocalTime startTime,
            LocalTime endTime,
            String excludeId)
            throws ExecutionException, InterruptedException {

        return countConflicts(
                "teacher.id", teacherId, day,
                startTime, endTime, excludeId
        );
    }

    public long countClassroomConflict(
            String classroomId,
            String day,
            LocalTime startTime,
            LocalTime endTime,
            String excludeId)
            throws ExecutionException, InterruptedException {

        return countConflicts(
                "classroom.id", classroomId, day,
                startTime, endTime, excludeId
        );
    }

    public long countCourseConflict(
            String courseId,
            String day,
            LocalTime startTime,
            LocalTime endTime,
            String excludeId)
            throws ExecutionException, InterruptedException {

        return countConflicts(
                "course.id", courseId, day,
                startTime, endTime, excludeId
        );
    }

    private long countConflicts(
            String field,
            String id,
            String day,
            LocalTime startTime,
            LocalTime endTime,
            String excludeId)
            throws ExecutionException, InterruptedException {

        long count = 0;

        List<QueryDocumentSnapshot> documents = firestore
                .collection("timetables")
                .whereEqualTo(field, id)
                .get()
                .get()
                .getDocuments();

        for (QueryDocumentSnapshot document : documents) {

            if (excludeId != null &&
                    excludeId.equals(document.getId())) {
                continue;
            }

            Timetable timetable = documentToTimetable(document);

            if (!day.equals(timetable.getDay())) {
                continue;
            }

            boolean overlap =
                    timetable.getStartTime().isBefore(endTime)
                    && timetable.getEndTime().isAfter(startTime);

            if (overlap) {
                count++;
            }
        }

        return count;
    }

    private Map<String, Object> teacherToMap(Teacher teacher) {

        Map<String, Object> map = new HashMap<>();

        map.put("id", teacher.getId());
        map.put("name", teacher.getName());
        map.put("subject", teacher.getSubject());
        map.put("department", teacher.getDepartment());

        return map;
    }

    private Map<String, Object> courseToMap(Course course) {

        Map<String, Object> map = new HashMap<>();

        map.put("id", course.getId());
        map.put("courseCode", course.getCourseCode());
        map.put("courseName", course.getCourseName());
        map.put("department", course.getDepartment());
        map.put("credits", course.getCredits());

        return map;
    }

    private Map<String, Object> classroomToMap(Classroom classroom) {

        Map<String, Object> map = new HashMap<>();

        map.put("id", classroom.getId());
        map.put("building", classroom.getBuilding());
        map.put("roomNumber", classroom.getRoomNumber());
        map.put("capacity", classroom.getCapacity());

        return map;
    }

    private Timetable documentToTimetable(DocumentSnapshot document) {

        Timetable timetable = new Timetable();

        timetable.setId(document.getId());
        timetable.setDay(document.getString("day"));

        timetable.setStartTime(
                LocalTime.parse(document.getString("startTime"))
        );

        timetable.setEndTime(
                LocalTime.parse(document.getString("endTime"))
        );

        timetable.setAutoGenerated(
                Boolean.TRUE.equals(document.getBoolean("autoGenerated"))
        );

        Map<String, Object> teacherData =
                (Map<String, Object>) document.get("teacher");

        if (teacherData != null) {
            Teacher teacher = new Teacher();

            teacher.setId((String) teacherData.get("id"));
            teacher.setName((String) teacherData.get("name"));
            teacher.setSubject((String) teacherData.get("subject"));
            teacher.setDepartment((String) teacherData.get("department"));

            timetable.setTeacher(teacher);
        }

        Map<String, Object> courseData =
                (Map<String, Object>) document.get("course");

        if (courseData != null) {
            Course course = new Course();

            course.setId((String) courseData.get("id"));
            course.setCourseCode((String) courseData.get("courseCode"));
            course.setCourseName((String) courseData.get("courseName"));
            course.setDepartment((String) courseData.get("department"));

            Object credits = courseData.get("credits");

            if (credits instanceof Number) {
                course.setCredits(((Number) credits).intValue());
            }

            timetable.setCourse(course);
        }

        Map<String, Object> classroomData =
                (Map<String, Object>) document.get("classroom");

        if (classroomData != null) {
            Classroom classroom = new Classroom();

            classroom.setId((String) classroomData.get("id"));
            classroom.setBuilding((String) classroomData.get("building"));
            classroom.setRoomNumber((String) classroomData.get("roomNumber"));

            Object capacity = classroomData.get("capacity");

            if (capacity instanceof Number) {
                classroom.setCapacity(((Number) capacity).intValue());
            }

            timetable.setClassroom(classroom);
        }

        return timetable;
    }
}
