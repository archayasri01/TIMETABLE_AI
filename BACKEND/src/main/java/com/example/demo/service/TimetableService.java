
package com.example.demo.service;

import com.example.demo.dto.TimetableRequest;
import com.example.demo.entity.Classroom;
import com.example.demo.entity.Course;
import com.example.demo.entity.Teacher;
import com.example.demo.entity.Timetable;
import com.example.demo.exception.ResourceNotFoundException;
import com.example.demo.exception.TimetableConflictException;
import com.example.demo.exception.TimetableNotFoundException;
import com.example.demo.exception.ValidationException;
import com.example.demo.repository.ClassroomRepository;
import com.example.demo.repository.CourseRepository;
import com.example.demo.repository.TeacherRepository;
import com.example.demo.repository.TimetableRepository;

import org.springframework.stereotype.Service;

import java.time.LocalTime;
import java.util.Arrays;
import java.util.List;
import java.util.concurrent.ExecutionException;

@Service
public class TimetableService {

    private static final List<String> VALID_DAYS = Arrays.asList(
            "Monday", "Tuesday", "Wednesday", "Thursday",
            "Friday", "Saturday", "Sunday"
    );

    private final TimetableRepository timetableRepository;
    private final TeacherRepository teacherRepository;
    private final CourseRepository courseRepository;
    private final ClassroomRepository classroomRepository;

    public TimetableService(
            TimetableRepository timetableRepository,
            TeacherRepository teacherRepository,
            CourseRepository courseRepository,
            ClassroomRepository classroomRepository) {

        this.timetableRepository = timetableRepository;
        this.teacherRepository = teacherRepository;
        this.courseRepository = courseRepository;
        this.classroomRepository = classroomRepository;
    }

    // Get all timetable records
    public List<Timetable> getAllTimetables() {
        return execute(() -> timetableRepository.findAll());
    }

    // Get timetable by ID
    public Timetable getTimetableById(String id) {
        return execute(() -> timetableRepository.findById(id))
                .orElseThrow(() ->
                        new TimetableNotFoundException("Timetable not found"));
    }

    // Get timetable by teacher
    public List<Timetable> getTimetablesByTeacher(String teacherId) {
        return execute(() -> timetableRepository.findByTeacherId(teacherId));
    }

    // Get timetable by course
    public List<Timetable> getTimetablesByCourse(String courseId) {
        return execute(() -> timetableRepository.findByCourseId(courseId));
    }

    // Get timetable by classroom
    public List<Timetable> getTimetablesByClassroom(String classroomId) {
        return execute(() -> timetableRepository.findByClassroomId(classroomId));
    }

    // Get timetable by day
    public List<Timetable> getTimetablesByDay(String day) {
        return execute(() ->
                timetableRepository.findByDayOrderByStartTimeAsc(day));
    }

    // Create timetable
    public Timetable createTimetable(
            TimetableRequest request,
            String teacherId,
            String courseId,
            String classroomId) {

        validateRequest(request);

        Teacher teacher = execute(() -> teacherRepository.findById(teacherId))
                .orElseThrow(() ->
                        new ResourceNotFoundException(
                                "Teacher not found with ID: " + teacherId));

        Course course = execute(() -> courseRepository.findById(courseId))
                .orElseThrow(() ->
                        new ResourceNotFoundException(
                                "Course not found with ID: " + courseId));

        Classroom classroom = execute(() -> classroomRepository.findById(classroomId))
                .orElseThrow(() ->
                        new ResourceNotFoundException(
                                "Classroom not found with ID: " + classroomId));

        checkConflicts(
                teacher.getId(),
                classroom.getId(),
                course.getId(),
                request.getDay(),
                request.getStartTime(),
                request.getEndTime(),
                null
        );

        Timetable timetable = new Timetable();

        timetable.setDay(capitalizeDay(request.getDay()));
        timetable.setStartTime(request.getStartTime());
        timetable.setEndTime(request.getEndTime());
        timetable.setAutoGenerated(request.isAutoGenerated());

        timetable.setTeacher(teacher);
        timetable.setCourse(course);
        timetable.setClassroom(classroom);

        return execute(() -> timetableRepository.save(timetable));
    }

    // Update timetable
    public Timetable updateTimetable(String id, TimetableRequest request) {

        Timetable existing = execute(() -> timetableRepository.findById(id))
                .orElseThrow(() ->
                        new TimetableNotFoundException("Timetable not found"));

        validateRequest(request);

        Teacher teacher = existing.getTeacher();

        if (request.getTeacherId() != null &&
                !request.getTeacherId().equals(teacher.getId())) {

            teacher = execute(() ->
                    teacherRepository.findById(request.getTeacherId()))
                    .orElseThrow(() ->
                            new ResourceNotFoundException(
                                    "Teacher not found with ID: "
                                            + request.getTeacherId()));
        }

        Course course = existing.getCourse();

        if (request.getCourseId() != null &&
                !request.getCourseId().equals(course.getId())) {

            course = execute(() ->
                    courseRepository.findById(request.getCourseId()))
                    .orElseThrow(() ->
                            new ResourceNotFoundException(
                                    "Course not found with ID: "
                                            + request.getCourseId()));
        }

        Classroom classroom = existing.getClassroom();

        if (request.getClassroomId() != null &&
                !request.getClassroomId().equals(classroom.getId())) {

            classroom = execute(() ->
                    classroomRepository.findById(request.getClassroomId()))
                    .orElseThrow(() ->
                            new ResourceNotFoundException(
                                    "Classroom not found with ID: "
                                            + request.getClassroomId()));
        }

        checkConflicts(
                teacher.getId(),
                classroom.getId(),
                course.getId(),
                request.getDay(),
                request.getStartTime(),
                request.getEndTime(),
                id
        );

        existing.setDay(capitalizeDay(request.getDay()));
        existing.setStartTime(request.getStartTime());
        existing.setEndTime(request.getEndTime());
        existing.setAutoGenerated(request.isAutoGenerated());

        existing.setTeacher(teacher);
        existing.setCourse(course);
        existing.setClassroom(classroom);

        return execute(() -> timetableRepository.save(existing));
    }

    // Delete timetable
    public void deleteTimetable(String id) {

        boolean exists = execute(() -> timetableRepository.existsById(id));

        if (!exists) {
            throw new TimetableNotFoundException("Timetable not found");
        }

        execute(() -> {
            timetableRepository.deleteById(id);
            return null;
        });
    }

    // Clear auto-generated timetables
    public void clearAutoGenerated() {
        execute(() -> {
            timetableRepository.deleteByAutoGeneratedTrue();
            return null;
        });
    }

    // Check teacher, classroom, and course conflicts
    public void checkConflicts(
            String teacherId,
            String classroomId,
            String courseId,
            String day,
            LocalTime startTime,
            LocalTime endTime,
            String excludeId) {

        String formattedDay = capitalizeDay(day);

        long teacherConflicts = execute(() ->
                timetableRepository.countTeacherConflict(
                        teacherId, formattedDay, startTime, endTime, excludeId));

        if (teacherConflicts > 0) {
            throw new TimetableConflictException(
                    "Teacher is already assigned during this time.");
        }

        long classroomConflicts = execute(() ->
                timetableRepository.countClassroomConflict(
                        classroomId, formattedDay, startTime, endTime, excludeId));

        if (classroomConflicts > 0) {
            throw new TimetableConflictException(
                    "Classroom is already occupied during this time.");
        }

        long courseConflicts = execute(() ->
                timetableRepository.countCourseConflict(
                        courseId, formattedDay, startTime, endTime, excludeId));

        if (courseConflicts > 0) {
            throw new TimetableConflictException(
                    "Course already has a timetable during this time.");
        }
    }

    // Validate timetable request
    private void validateRequest(TimetableRequest request) {

        if (request == null) {
            throw new ValidationException("Timetable request is required");
        }

        if (request.getDay() == null ||
                request.getDay().trim().isEmpty()) {
            throw new ValidationException("Day is required");
        }

        if (!isValidDay(request.getDay())) {
            throw new ValidationException(
                    "Invalid day: " + request.getDay());
        }

        if (request.getStartTime() == null) {
            throw new ValidationException("Start time is required");
        }

        if (request.getEndTime() == null) {
            throw new ValidationException("End time is required");
        }

        if (!request.getStartTime().isBefore(request.getEndTime())) {
            throw new ValidationException(
                    "Start time must be before end time");
        }
    }

    // Validate day
    private boolean isValidDay(String day) {

        if (day == null) {
            return false;
        }

        for (String validDay : VALID_DAYS) {
            if (validDay.equalsIgnoreCase(day.trim())) {
                return true;
            }
        }

        return false;
    }

    // Normalize day
    private String capitalizeDay(String day) {

        for (String validDay : VALID_DAYS) {
            if (validDay.equalsIgnoreCase(day.trim())) {
                return validDay;
            }
        }

        return day.trim();
    }

    // Count timetable records
    public long count() {
        return execute(() -> timetableRepository.count());
    }

    // Handle Firestore checked exceptions centrally
    @FunctionalInterface
    private interface FirestoreOperation<T> {
        T run() throws ExecutionException, InterruptedException;
    }

    private <T> T execute(FirestoreOperation<T> operation) {

        try {
            return operation.run();

        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException(
                    "Firestore operation was interrupted", e);

        } catch (ExecutionException e) {
            throw new IllegalStateException(
                    "Firestore operation failed", e);
        }
    }
}
